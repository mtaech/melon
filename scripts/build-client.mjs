/**
 * Bundle the browser half (src/client/main.ts) into the ModuleLoader factory
 * form dsh's web GUI expects: window.__ModuleLoader__.load({ id, factory }).
 * The factory receives `require`, which resolves platform modules (react,
 * @deepseek-ai/*) from the shell; esbuild marks them external and emits a CJS
 * bundle whose module/exports/require bindings live inside the factory scope.
 */
import { buildSync } from "esbuild";
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const result = buildSync({
	entryPoints: [path.join(root, "src", "client", "main.ts")],
	bundle: true,
	format: "cjs",
	platform: "browser",
	target: ["es2022"],
	write: false,
	external: ["react", "react-dom", "react-dom/*", "react/jsx-runtime", "@deepseek-ai/*"],
	sourcemap: false,
	logLevel: "warning",
});

const body = result.outputFiles[0].text;
const wrapped = [
	"/** Generated by scripts/build-client.mjs — do not edit. */",
	"window.__ModuleLoader__.load({",
	'	id: "dsh-plugin-dashboard",',
	"	factory: (require) => {",
	body,
	"	}",
	"});",
	"",
].join("\n");

mkdirSync(path.join(root, "lib"), { recursive: true });
writeFileSync(path.join(root, "lib", "client.cjs"), wrapped);
console.log(`lib/client.cjs (${wrapped.length} bytes)`);